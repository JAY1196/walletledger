#!/bin/sh
set -eu

mysql \
  --protocol=socket \
  -uroot \
  --password="${MYSQL_ROOT_PASSWORD}" \
  "${MYSQL_DATABASE}" <<SQL

CREATE USER IF NOT EXISTS '${MYSQL_OWNER_USER}'@'%'
  IDENTIFIED BY '${MYSQL_OWNER_PASSWORD}';

GRANT ALL PRIVILEGES ON ${MYSQL_DATABASE}.*
  TO '${MYSQL_OWNER_USER}'@'%';

CREATE USER IF NOT EXISTS '${MYSQL_APP_USER}'@'%'
  IDENTIFIED BY '${MYSQL_APP_PASSWORD}';

GRANT SELECT, INSERT, UPDATE, DELETE ON ${MYSQL_DATABASE}.*
  TO '${MYSQL_APP_USER}'@'%';

FLUSH PRIVILEGES;

SQL

echo "WalletLedger MySQL users initialized."